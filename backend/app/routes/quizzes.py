@router.post("/generate", response_model=QuizResponse, status_code=status.HTTP_201_CREATED)
def generate_quiz(
    req: QuizGenerateRequest,
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    source_text = req.topic or ""
    quiz_topic = req.topic or "Academic Assessment"

    if req.document_id:
        doc = db.query(Document).filter(
            Document.id == req.document_id,
            Document.user_id == current_user.id
        ).first()

        if not doc:
            raise HTTPException(status_code=404, detail="Selected document not found.")

        quiz_topic = req.topic or doc.title
        if doc.extracted_text:
            try:
                pages_data = json.loads(doc.extracted_text)
                source_text = "\n\n".join([f"Page {p['page']}: {p['text']}" for p in pages_data[:8]])
            except Exception:
                source_text = doc.extracted_text
        else:
            raise HTTPException(status_code=400, detail="Document has no extracted text to generate quiz from.")

    if not source_text.strip():
        raise HTTPException(status_code=400, detail="Please provide a topic or select a document.")

    # Call Gemini to generate quiz
    questions_data = gemini_service.generate_quiz(
        topic_or_doc=source_text,
        difficulty=req.difficulty,
        question_count=req.question_count,
        question_type=req.question_type
    )

    if not questions_data:
        raise HTTPException(status_code=502, detail="No quiz questions were generated by AI.")

    # Approximate time limit: 1.5 minutes per question
    time_limit = max(5, int(len(questions_data) * 1.5))

    # Save Quiz to DB
    quiz = Quiz(
        user_id=current_user.id,
        document_id=req.document_id,
        topic=quiz_topic,
        difficulty=req.difficulty,
        question_count=len(questions_data),
        time_limit_minutes=time_limit
    )
    db.add(quiz)
    db.flush()

    saved_questions = []
    for q in questions_data:
        raw_options = q.get("options", [])
        if not raw_options and q.get("question_type") == "true_false":
            raw_options = ["True", "False"]

        question_record = QuizQuestion(
            quiz_id=quiz.id,
            question_text=q.get("question_text", "Question"),
            question_type=q.get("question_type", "mcq"),
            options=json.dumps(raw_options) if raw_options else None,
            correct_answer=str(q.get("correct_answer", "")).strip(),
            explanation=q.get("explanation", ""),
            topic_tag=q.get("topic_tag", quiz_topic)
        )
        db.add(question_record)
        db.flush()

        saved_questions.append({
            "id": question_record.id,
            "question_text": question_record.question_text,
            "question_type": question_record.question_type,
            "options": raw_options,
            "topic_tag": question_record.topic_tag
        })

    db.commit()

    return {
        "id": quiz.id,
        "topic": quiz.topic,
        "difficulty": quiz.difficulty,
        "question_count": quiz.question_count,
        "time_limit_minutes": quiz.time_limit_minutes,
        "document_id": quiz.document_id,
        "created_at": quiz.created_at,
        "questions": saved_questions
    }

@router.get("", response_model=List[QuizResponse])
def get_quizzes(
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    quizzes = db.query(Quiz).filter(
        Quiz.user_id == current_user.id
    ).order_by(Quiz.created_at.desc()).all()

    result = []
    for q in quizzes:
        q_records = db.query(QuizQuestion).filter(QuizQuestion.quiz_id == q.id).all()
        q_list = []
        for qr in q_records:
            opts = []
            if qr.options:
                try: opts = json.loads(qr.options)
                except Exception: pass
            q_list.append({
                "id": qr.id,
                "question_text": qr.question_text,
                "question_type": qr.question_type,
                "options": opts,
                "topic_tag": qr.topic_tag
            })
        result.append({
            "id": q.id,
            "topic": q.topic,
            "difficulty": q.difficulty,
            "question_count": q.question_count,
            "time_limit_minutes": q.time_limit_minutes,
            "document_id": q.document_id,
            "created_at": q.created_at,
            "questions": q_list
        })
    return result

