@router.post("/{quiz_id}/submit", response_model=QuizResultResponse)
def submit_quiz(
    quiz_id: int,
    sub_data: QuizSubmitRequest,
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    quiz = db.query(Quiz).filter(
        Quiz.id == quiz_id,
        Quiz.user_id == current_user.id
    ).first()

    if not quiz:
        raise HTTPException(status_code=404, detail="Quiz not found.")

    questions = db.query(QuizQuestion).filter(QuizQuestion.quiz_id == quiz.id).all()
    questions_map = {q.id: q for q in questions}

    user_answers_dict = {a.question_id: a.selected_answer for a in sub_data.answers}
    correct_count = 0
    weak_topics = []
    detailed_questions = []

    for q in questions:
        user_choice = str(user_answers_dict.get(q.id, "")).strip().lower()
        correct_choice = str(q.correct_answer).strip().lower()

        is_correct = (user_choice == correct_choice)
        if is_correct:
            correct_count += 1
        else:
            if q.topic_tag and q.topic_tag not in weak_topics:
                weak_topics.append(q.topic_tag)

        opts = []
        if q.options:
            try: opts = json.loads(q.options)
            except Exception: pass

        detailed_questions.append({
            "id": q.id,
            "question_text": q.question_text,
            "question_type": q.question_type,
            "options": opts,
            "correct_answer": q.correct_answer,
            "explanation": q.explanation,
            "topic_tag": q.topic_tag
        })

    total_q = len(questions)
    percentage = round((correct_count / total_q * 100), 1) if total_q > 0 else 0.0

    # Suggestions based on performance
    if percentage >= 90:
        suggestions = "Outstanding mastery! You have demonstrated deep command of these concepts. Proceed to higher difficulty or explore new units."
    elif percentage >= 70:
        suggestions = "Solid performance! Review the questions you missed and reinforce the key formulas and edge cases before the examination."
    elif percentage >= 50:
        suggestions = "Average understanding. Focus on the identified weak topics using the Document Intelligence workspace and regenerate a short revision quiz."
    else:
        suggestions = "Foundational concepts need strengthening. Re-read the source notes in Beginner Mode and attempt practice questions again."

    # Record attempt in DB
    attempt = QuizAttempt(
        quiz_id=quiz.id,
        user_id=current_user.id,
        score=correct_count,
        total_questions=total_q,
        percentage=percentage,
        time_taken_seconds=sub_data.time_taken_seconds,
        answers=json.dumps(user_answers_dict),
        weak_topics=json.dumps(weak_topics),
        suggestions=suggestions,
        completed_at=datetime.now(timezone.utc)
    )
    db.add(attempt)
    db.commit()
    db.refresh(attempt)

    # Log learning activity
    duration_mins = max(5, int(sub_data.time_taken_seconds / 60))
    analytics_service.log_activity(
        db=db,
        user_id=current_user.id,
        activity_type="quiz_completed",
        title=f"Completed Quiz: {quiz.topic} ({percentage}%)",
        details=f"Scored {correct_count}/{total_q} in {duration_mins}m.",
        duration_minutes=duration_mins
    )

    return {
        "attempt_id": attempt.id,
        "quiz_id": quiz.id,
        "score": correct_count,
        "total_questions": total_q,
        "percentage": percentage,
        "time_taken_seconds": sub_data.time_taken_seconds,
        "weak_topics": weak_topics,
        "suggestions": suggestions,
        "completed_at": attempt.completed_at,
        "detailed_questions": detailed_questions,
        "user_answers": user_answers_dict
    }

@router.get("/history/all", response_model=List[QuizHistoryItem])
def get_quiz_history(
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    attempts = db.query(QuizAttempt).filter(
        QuizAttempt.user_id == current_user.id
    ).order_by(QuizAttempt.completed_at.desc()).all()

    result = []
    for att in attempts:
        quiz = db.query(Quiz).filter(Quiz.id == att.quiz_id).first()
        topic_name = quiz.topic if quiz else "Assessment"
        diff = quiz.difficulty if quiz else "medium"
        result.append({
            "attempt_id": att.id,
            "quiz_id": att.quiz_id,
            "topic": topic_name,
            "difficulty": diff,
            "score": att.score,
            "total_questions": att.total_questions,
            "percentage": att.percentage,
            "completed_at": att.completed_at
        })
    return result

